package com.dnd.app.domain.enums;

/**
 * Перечисление RollPromptType описывает тип запрошенной мастером проверки (ROLL_PROMPT):
 * проверка характеристики, спасбросок или произвольный d20 без модификатора персонажа.
 */
public enum RollPromptType {
    /** Проверка характеристики: d20 + модификатор характеристики (с баффами/фичами). */
    ABILITY_CHECK,
    /** Спасбросок: d20 + модификатор характеристики + бонус мастерства при владении. */
    SAVING_THROW,
    /** Произвольный бросок: чистый d20 без модификатора персонажа. */
    CUSTOM
}
