package com.dnd.app.domain.enums;

/**
 * Перечисление DialogueActionType описывает действие варианта ответа в диалоге NPC
 * (WORLD_PLAN Этап 4). Действие лишь переключает игрока на уже защищённые бэком разделы
 * взаимодействия — самих прав оно не выдаёт.
 */
public enum DialogueActionType {
    /** Завершить разговор. */
    END,
    /** Открыть витрину торговца. */
    OPEN_SHOP,
    /** Перейти к квестам NPC (взять/сдать — по обычным правилам). */
    OFFER_QUEST
}
