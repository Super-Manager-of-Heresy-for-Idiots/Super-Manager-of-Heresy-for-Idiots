package com.dnd.app.domain.enums;

/**
 * Перечисление CampActivityKind описывает происхождение даунтайм-активности:
 * системная (доступна всем кампаниям) либо кастомная, созданная мастером кампании.
 * Значение вычисляется из принадлежности активности кампании и не хранится отдельной колонкой.
 */
public enum CampActivityKind {
    SYSTEM,
    CUSTOM
}
