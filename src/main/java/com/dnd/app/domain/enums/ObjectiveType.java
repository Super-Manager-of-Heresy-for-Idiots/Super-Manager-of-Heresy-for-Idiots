package com.dnd.app.domain.enums;

/**
 * Перечисление ObjectiveType описывает тип опциональной цели квеста (WORLD_PLAN Этап 3).
 * Мастер задаёт цели по желанию. {@code COLLECT_ITEM} проверяется автоматически по инвентарю
 * персонажа; прогресс остальных типов проставляет мастер вручную (по своему усмотрению).
 */
public enum ObjectiveType {
    /** Убить монстров/существ (target_ref — ссылка на бестиарий; прогресс ставит мастер). */
    KILL_MONSTER,
    /** Собрать предметы (target_ref — item_template; проверяется автоматически по инвентарю). */
    COLLECT_ITEM,
    /** Поговорить с NPC (target_ref — campaign_npc; прогресс ставит мастер). */
    TALK_TO_NPC,
    /** Посетить локацию (target_ref — campaign_location; прогресс ставит мастер). */
    VISIT_LOCATION,
    /** Произвольная цель с текстовым описанием (прогресс ставит мастер). */
    CUSTOM
}
